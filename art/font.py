SPACE = 3   # width of a space, in art pixels


def rects(rows):
    """Each horizontal run of ink as (x, y_from_top, width)."""
    out = []
    for y, r in enumerate(rows):
        x = 0
        while x < len(r):
            if r[x] == '#':
                s = x
                while x < len(r) and r[x] == '#':
                    x += 1
                out.append((s, y, x - s))
            else:
                x += 1
    return out


def glyph(rows):
    pen = TTGlyphPen(None)
    for x, y, w in rects(rows):
        top = (ASC - y) * UNIT
        x0, x1, y0 = x * UNIT, (x + w) * UNIT, top - UNIT
        pen.moveTo((x0, y0)); pen.lineTo((x0, top)); pen.lineTo((x1, top)); pen.lineTo((x1, y0)); pen.closePath()
    return pen.glyph()


def build():
    names = ['.notdef', 'space']
    cmap = {32: 'space', 160: 'space'}
    glyphs = {'.notdef': glyph(['####', '#..#', '#..#', '#..#', '#..#', '#..#', '####']), 'space': TTGlyphPen(None).glyph()}
    metrics = {'.notdef': (5 * UNIT, 0), 'space': (SPACE * UNIT, 0)}
    for ch, rows in GLYPHS.items():
        n = 'uni%04X' % ord(ch)
        names.append(n); cmap[ord(ch)] = n
        glyphs[n] = glyph(rows)
        w = max([len(r) for r in rows] + [1])
        metrics[n] = ((w + 1) * UNIT, 0)
    fb = FontBuilder(unitsPerEm=(ASC + DESC) * UNIT, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=ASC * UNIT, descent=-DESC * UNIT)
    fb.setupNameTable({'familyName': 'TBD Pixel', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=ASC * UNIT, sTypoDescender=-DESC * UNIT, usWinAscent=ASC * UNIT, usWinDescent=DESC * UNIT, sTypoLineGap=0)
    fb.setupPost()
    fb.font.flavor = 'woff'
    os.makedirs(OUT, exist_ok=True)
    fb.save(os.path.join(OUT, 'tbd-pixel.woff'))


def preview():
    text = ['TEST TBD - Play solo · Create lobby', 'The quick brown fox jumps over the lazy dog?', 'Gold 1,234  Wave 12 / 20  +25% ×2 ✓ ▲ →  (0-9): 0123456789']
    s = 3
    img = Image.new('RGBA', (1400, 3 * 12 * s + 20), (24, 33, 28, 255))
    px = img.load()
    for li, line in enumerate(text):
        cx = 10
        for ch in line:
            if ch == ' ':
                cx += (SPACE) * s; continue
            rows = GLYPHS.get(ch)
            if not rows:
                cx += 6 * s; continue
            for x, y, w in rects(rows):
                for dx in range(w * s):
                    for dy in range(s):
                        X, Y = cx + x * s + dx, 10 + li * 12 * s + y * s + dy
                        if X < img.width and Y < img.height:
                            px[X, Y] = (236, 241, 232, 255)
            cx += (max(len(r) for r in rows) + 1) * s
    img.save(os.path.join(OUT, 'preview-font.png'))


