/* Builds supabase-setup.sql (new projects) and supabase-update.sql (existing projects) from the parts in sql/ plus the
   game content and rules in js/content (tools/content-sql.mjs, tools/rules-sql.mjs). Run after changing any of them:   npm run sql
   A test fails if the committed files are out of date. */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { contentSeedSql } from './content-sql.mjs';
import { rulesSql, rulesPermissionsSql } from './rules-sql.mjs';

const root = new URL('../', import.meta.url);
const part = name => readFileSync(new URL('sql/' + name, root), 'utf8').trim() + '\n';
const names = readdirSync(new URL('sql/', root)).filter(f => f.endsWith('.sql')).sort();

/* Which parts go in which file: 10 and 60 only for new projects, 15 only for existing ones. */
const NEW_ONLY = ['10-profiles.sql', '60-trigger.sql'], EXISTING_ONLY = ['15-migrate.sql'];
const CONTENT_AFTER = '30-tables.sql';

function build(kind) {
  const header = kind === 'setup'
    ? '-- Test TBD: full database setup for a NEW project. Run once in Supabase (SQL Editor > New query > paste > Run).\n-- Already set up earlier? Run supabase-update.sql instead.\n'
    : '-- Test TBD: update for an EXISTING project. Run in Supabase (SQL Editor > New query > paste > Run). Safe to run more than once.\n-- It never deletes players or their progress. (To remove the old prototype tables, see supabase-cleanup-old-prototypes.sql.)\n';
  const out = [header, '-- Generated by tools/build-sql.mjs from the files in sql/ and js/content. Edit those, then run: npm run sql\n'];
  for (const n of names) {
    if (kind === 'setup' && EXISTING_ONLY.includes(n)) continue;
    if (kind === 'update' && NEW_ONLY.includes(n)) continue;
    out.push(part(n));
    if (n === CONTENT_AFTER) { out.push(contentSeedSql()); out.push(rulesSql()); }
    if (n === '70-permissions.sql') out.push(rulesPermissionsSql());
  }
  return out.join('\n');
}

export const buildSetup = () => build('setup');
export const buildUpdate = () => build('update');

if (import.meta.url === 'file://' + process.argv[1] || process.argv[1]?.endsWith('build-sql.mjs')) {
  writeFileSync(new URL('supabase-setup.sql', root), buildSetup());
  writeFileSync(new URL('supabase-update.sql', root), buildUpdate());
  console.log('Wrote supabase-setup.sql and supabase-update.sql');
}
